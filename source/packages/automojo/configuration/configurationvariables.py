def resolve_configuration_variables():

    # We need to resolve extension variables because we are
    # dependent on some of them.
    resolve_runtime_variables()

    environ = os.environ

    ctx = ContextSingleton()

    # For now, we don't want to put the CREDENTIALS CONFIGURATION into the context, because at the moment we don't 
    # want to pass it around in the plain.  Possibly what we can do is create a version of MergeMap that will serialize
    # with a protective pass key or something like that.
    ctx.insert(ContextPaths.CONFIG_DATAPROFILES, CONFIGURATION_MAPS.DATAPROFILE_CONFIGURATION_MAP)
    ctx.insert(ContextPaths.CONFIG_LANDSCAPE, CONFIGURATION_MAPS.LANDSCAPE_CONFIGURATION_MAP)
    ctx.insert(ContextPaths.CONFIG_TOPOLOGY, CONFIGURATION_MAPS.TOPOLOGY_CONFIGURATION_MAP)
    ctx.insert(ContextPaths.CONFIG_RUNTIME, CONFIGURATION_MAPS.RUNTIME_CONFIGURATION_MAP)


    AM_CONFIG_VARIABLES.AM_CONFIG_DIRECTORY = os.path.join(AM_CONFIG_VARIABLES.AM_PRESENCE_DIRECTORY, "config")
    if AM_CONFIG_VARNAMES.AM_CONFIG_DIRECTORY in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_DIRECTORY = environ[AM_CONFIG_VARNAMES.AM_CONFIG_DIRECTORY]
    ctx.insert(ContextPaths.PRESENCE_CONFIG_DIRECTORY, AM_CONFIG_VARIABLES.AM_CONFIG_DIRECTORY)


    if AM_CONFIG_VARNAMES.AM_CONFIG_STORAGE_URI in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_STORAGE_URI = environ[AM_CONFIG_VARNAMES.AM_CONFIG_STORAGE_URI]
    ctx.insert(ContextPaths.CONFIG_STORAGE_URI, AM_CONFIG_VARIABLES.AM_CONFIG_STORAGE_URI)

    # ====================== PROCESS CREDENTIAL VARIABLES ==============================

    if AM_CONFIG_VARNAMES.AM_CONFIG_CREDENTIAL_FILES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_CREDENTIALS = True
        AM_CONFIG_VARIABLES.AM_CONFIG_CREDENTIAL_FILES = split_and_normalize_path_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_CREDENTIAL_FILES])

    if AM_CONFIG_VARNAMES.AM_CONFIG_CREDENTIAL_NAMES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_CREDENTIALS = True
        AM_CONFIG_VARIABLES.AM_CONFIG_CREDENTIAL_NAMES = split_and_normalize_name_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_CREDENTIAL_NAMES])
    elif AM_CONFIG_DEFAULTS.AM_CONFIG_REQUIRE_CREDENTIALS:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_CREDENTIALS = True

    if AM_CONFIG_VARNAMES.AM_CONFIG_CREDENTIAL_SOURCES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_CREDENTIAL_SOURCES = split_and_normalize_source_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_CREDENTIAL_SOURCES])
    else:
        AM_CONFIG_VARIABLES.AM_CONFIG_CREDENTIAL_SOURCES = [
            os.path.join(AM_CONFIG_VARIABLES.AM_CONFIG_DIRECTORY, "credentials")
        ]
    
    ctx.insert(ContextPaths.CONFIG_CREDENTIAL_FILES, AM_CONFIG_VARIABLES.AM_CONFIG_CREDENTIAL_FILES)
    ctx.insert(ContextPaths.CONFIG_CREDENTIAL_NAMES, AM_CONFIG_VARIABLES.AM_CONFIG_CREDENTIAL_NAMES)
    ctx.insert(ContextPaths.CONFIG_CREDENTIAL_SOURCES, AM_CONFIG_VARIABLES.AM_CONFIG_CREDENTIAL_SOURCES)
    
    # ====================== PROCESS DATAPROFILE VARIABLES ==============================

    if AM_CONFIG_VARNAMES.AM_CONFIG_DATAPROFILE_FILES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_DATAPROFILES = True
        AM_CONFIG_VARIABLES.AM_CONFIG_DATAPROFILE_FILES = split_and_normalize_path_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_DATAPROFILE_FILES])

    if AM_CONFIG_VARNAMES.AM_CONFIG_DATAPROFILE_NAMES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_DATAPROFILES = True
        AM_CONFIG_VARIABLES.AM_CONFIG_DATAPROFILE_NAMES = split_and_normalize_name_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_DATAPROFILE_NAMES])
    elif AM_CONFIG_DEFAULTS.AM_CONFIG_REQUIRE_DATAPROFILES:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_DATAPROFILES = True

    if AM_CONFIG_VARNAMES.AM_CONFIG_DATAPROFILE_SOURCES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_DATAPROFILE_SOURCES = split_and_normalize_source_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_DATAPROFILE_SOURCES])
    else:
        AM_CONFIG_VARIABLES.AM_CONFIG_DATAPROFILE_SOURCES = [
            os.path.join(AM_CONFIG_VARIABLES.AM_CONFIG_DIRECTORY, "dataprofiles")
        ]
    
    ctx.insert(ContextPaths.CONFIG_DATAPROFILE_FILES, AM_CONFIG_VARIABLES.AM_CONFIG_DATAPROFILE_FILES)
    ctx.insert(ContextPaths.CONFIG_DATAPROFILE_NAMES, AM_CONFIG_VARIABLES.AM_CONFIG_DATAPROFILE_NAMES)
    ctx.insert(ContextPaths.CONFIG_DATAPROFILE_SOURCES, AM_CONFIG_VARIABLES.AM_CONFIG_DATAPROFILE_SOURCES)
    
    # ====================== PROCESS LANDSCAPE VARIABLES ==============================

    if AM_CONFIG_VARNAMES.AM_CONFIG_LANDSCAPE_FILES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_LANDSCAPE = True
        AM_CONFIG_VARIABLES.AM_CONFIG_LANDSCAPE_FILES = split_and_normalize_path_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_LANDSCAPE_FILES])

    if AM_CONFIG_VARNAMES.AM_CONFIG_LANDSCAPE_NAMES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_LANDSCAPE = True
        AM_CONFIG_VARIABLES.AM_CONFIG_LANDSCAPE_NAMES = split_and_normalize_name_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_LANDSCAPE_NAMES])
    elif AM_CONFIG_DEFAULTS.AM_CONFIG_REQUIRE_LANDSCAPE:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_LANDSCAPE = True

    if AM_CONFIG_VARNAMES.AM_CONFIG_LANDSCAPE_SOURCES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_LANDSCAPE_SOURCES = split_and_normalize_source_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_LANDSCAPE_SOURCES])
    else:
        AM_CONFIG_VARIABLES.AM_CONFIG_LANDSCAPE_SOURCES = [
            os.path.join(AM_CONFIG_VARIABLES.AM_CONFIG_DIRECTORY, "landscapes")
        ]

    ctx.insert(ContextPaths.CONFIG_LANDSCAPE_FILES, AM_CONFIG_VARIABLES.AM_CONFIG_LANDSCAPE_FILES)
    ctx.insert(ContextPaths.CONFIG_LANDSCAPE_NAMES, AM_CONFIG_VARIABLES.AM_CONFIG_LANDSCAPE_NAMES)
    ctx.insert(ContextPaths.CONFIG_LANDSCAPE_SOURCES, AM_CONFIG_VARIABLES.AM_CONFIG_LANDSCAPE_SOURCES)
    
    # ====================== PROCESS RUNTIME VARIABLES ==============================

    if AM_CONFIG_VARNAMES.AM_CONFIG_RUNTIME_FILES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_RUNTIME = True
        AM_CONFIG_VARIABLES.AM_CONFIG_RUNTIME_FILES = split_and_normalize_path_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_RUNTIME_FILES])

    if AM_CONFIG_VARNAMES.AM_CONFIG_RUNTIME_NAMES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_RUNTIME = True
        AM_CONFIG_VARIABLES.AM_CONFIG_RUNTIME_NAMES = split_and_normalize_name_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_RUNTIME_NAMES])
    elif AM_CONFIG_DEFAULTS.AM_CONFIG_REQUIRE_RUNTIME:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_RUNTIME = True

    if AM_CONFIG_VARNAMES.AM_CONFIG_RUNTIME_SOURCES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_RUNTIME_SOURCES = split_and_normalize_source_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_RUNTIME_SOURCES])
    else:
        AM_CONFIG_VARIABLES.AM_CONFIG_RUNTIME_SOURCES = [
            os.path.join(AM_CONFIG_VARIABLES.AM_CONFIG_DIRECTORY, "runtimes")
        ]

    ctx.insert(ContextPaths.CONFIG_RUNTIME_FILES, AM_CONFIG_VARIABLES.AM_CONFIG_RUNTIME_FILES)
    ctx.insert(ContextPaths.CONFIG_RUNTIME_NAMES, AM_CONFIG_VARIABLES.AM_CONFIG_RUNTIME_NAMES)
    ctx.insert(ContextPaths.CONFIG_RUNTIME_SOURCES, AM_CONFIG_VARIABLES.AM_CONFIG_RUNTIME_SOURCES)
    
    # ====================== PROCESS TOPOLOGY VARIABLES ==============================

    if AM_CONFIG_VARNAMES.AM_CONFIG_TOPOLOGY_FILES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_TOPOLOGY = True
        AM_CONFIG_VARIABLES.AM_CONFIG_TOPOLOGY_FILES = split_and_normalize_path_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_TOPOLOGY_FILES])

    if AM_CONFIG_VARNAMES.AM_CONFIG_TOPOLOGY_NAMES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_TOPOLOGY = True
        AM_CONFIG_VARIABLES.AM_CONFIG_TOPOLOGY_NAMES = split_and_normalize_name_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_TOPOLOGY_NAMES])
    elif AM_CONFIG_DEFAULTS.AM_CONFIG_REQUIRE_RUNTIME:
        AM_CONFIG_VARIABLES.AM_CONFIG_USE_RUNTIME = True

    if AM_CONFIG_VARNAMES.AM_CONFIG_TOPOLOGY_SOURCES in environ:
        AM_CONFIG_VARIABLES.AM_CONFIG_TOPOLOGY_SOURCES = split_and_normalize_source_list(
            environ[AM_CONFIG_VARNAMES.AM_CONFIG_TOPOLOGY_SOURCES])
    else:
        AM_CONFIG_VARIABLES.AM_CONFIG_TOPOLOGY_SOURCES = [
            os.path.join(AM_CONFIG_VARIABLES.AM_CONFIG_DIRECTORY, "topologies")
        ]

    ctx.insert(ContextPaths.CONFIG_TOPOLOGY_FILES, AM_CONFIG_VARIABLES.AM_CONFIG_TOPOLOGY_FILES)
    ctx.insert(ContextPaths.CONFIG_TOPOLOGY_NAMES, AM_CONFIG_VARIABLES.AM_CONFIG_TOPOLOGY_NAMES)
    ctx.insert(ContextPaths.CONFIG_TOPOLOGY_SOURCES, AM_CONFIG_VARIABLES.AM_CONFIG_TOPOLOGY_SOURCES)

    return
